const studyTermsByKey = new Map(Object.entries(zhStudyTerms).map(([key, text])=>[key.toLowerCase(), text]));
const studyTermPattern = new RegExp(
  "(?<![a-zA-Z0-9_])(?:" + Object.keys(zhStudyTerms)
    .sort((a, b)=>b.length - a.length)
    .map(key=>key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("|") + ")(?![a-zA-Z0-9_])", "gi"
);

// For display only. Source URLs, record IDs, reference data and computed metrics use original values.
function zhStudyText(value) {
  if (typeof value !== "string") return value;
  if (Object.hasOwn(zhStudyPortions, value)) return zhStudyPortions[value];
  return value
    .replace(/\b(\d+) healthy participants\b/gi, "$1名健康受试者")
    .replace(/\b(\d+) T2DM participants\b/g, "$1名2型糖尿病受试者")
    .replace(/\b(\d+) NIDDM participants\b/g, "$1名非胰岛素依赖型糖尿病受试者")
    .replace(/\bC: ([\d.]+) M: ([\d.]+) I: ([\d.]+)/g, "华裔组 $1、马来裔组 $2、印度裔组 $3")
    .replace(/\/(\d+(?:\.\d+)?) hr?\b/g, "／$1小时")
    .replace(/\bNo\. (\d+)/g, "第$1项")
    .replace(/\bn\s*=\s*(\d+)/g, "样本量 $1")
    .replace(/（SEM）/g, "")
    .replace(studyTermPattern, term=>studyTermsByKey.get(term.toLowerCase()));
}
